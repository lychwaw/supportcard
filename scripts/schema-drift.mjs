#!/usr/bin/env node
/**
 * Emits a read-only SQL script that reports which policies and functions the
 * migrations declare but the database does not have.
 *
 * Why this exists: files in supabase/migrations/ are not a record of what the
 * live project contains. Several have never been applied — one sorted before
 * the CREATE TABLE it altered, another was simply never pushed — and nothing
 * in the repo distinguishes them from the ones that ran. The failures are
 * silent: a select against a missing column comes back as an error the client
 * treats as "no rows", so the screen renders empty forever instead of
 * reporting a fault.
 *
 * Columns and tables are already checkable — regenerate the types
 * (npx supabase gen types typescript --project-id <id>) and that file IS the
 * live schema. Policies and functions appear nowhere in it, which is what this
 * covers.
 *
 *   node scripts/schema-drift.mjs            # print the SQL
 *   node scripts/schema-drift.mjs -o out.sql # write it to a file
 *
 * Then run the output in the Supabase SQL editor. Nothing returned means
 * everything is applied.
 */

import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { join } from 'node:path';

const MIGRATIONS = 'supabase/migrations';

const files = readdirSync(MIGRATIONS).filter((f) => f.endsWith('.sql')).sort();

/** @type {Map<string, string>} key -> the migration that last did it */
const created = new Map();
const dropped = new Map();
const functions = new Map();

// "ON storage.objects" means schema storage, table objects. An earlier version
// of this check captured the schema as the table name and then looked for it
// in public, which reported every storage policy as missing.
const qualify = (raw) => {
  const parts = raw.split('.');
  return parts.length > 1
    ? { schema: parts[0].toLowerCase(), table: parts[1].toLowerCase() }
    : { schema: 'public', table: parts[0].toLowerCase() };
};

for (const file of files) {
  const sql = readFileSync(join(MIGRATIONS, file), 'utf8').replace(/--[^\n]*/g, '');

  for (const m of sql.matchAll(/create\s+policy\s+"([^"]+)"\s+on\s+([\w.]+)/gi)) {
    const { schema, table } = qualify(m[2]);
    created.set(`${schema}\u0000${table}\u0000${m[1]}`, file);
  }
  for (const m of sql.matchAll(/drop\s+policy\s+(?:if\s+exists\s+)?"([^"]+)"\s+on\s+([\w.]+)/gi)) {
    const { schema, table } = qualify(m[2]);
    dropped.set(`${schema}\u0000${table}\u0000${m[1]}`, file);
  }
  for (const m of sql.matchAll(/create\s+(?:or\s+replace\s+)?function\s+(?:public\.)?(\w+)/gi)) {
    functions.set(m[1], file);
  }
}

// A policy whose last DROP comes after its last CREATE was retired on purpose.
// Same-file drop-then-create is the normal idempotent pattern, so <= keeps it.
const expected = [...created]
  .filter(([key, createdIn]) => (dropped.get(key) ?? '') <= createdIn)
  .map(([key]) => key.split('\u0000'))
  .sort((a, b) => a.join().localeCompare(b.join()));

const lit = (s) => `'${s.replace(/'/g, "''")}'`;
const policyRows = expected.map(([s, t, p]) => `    (${lit(s)},${lit(t)},${lit(p)})`).join(',\n');
const fnRows = [...functions.keys()].sort().map((n) => `    (${lit(n)})`).join(',\n');

const out = `-- Generated by scripts/schema-drift.mjs — do not edit by hand.
-- Checks ${expected.length} policies and ${functions.size} functions declared in
-- ${MIGRATIONS}/ against what the database actually has.
--
-- NOTHING RETURNED = everything applied.
-- Any row = that migration never ran.
--
-- Read-only: two SELECTs against the system catalogs. It reads no application
-- data and changes nothing.
--
-- A missing NAME is not automatically a bug. A policy is often replaced by a
-- differently named one that covers the same operation, and a function nothing
-- calls does not matter. Before acting on a row, check whether the operation is
-- still covered:
--
--   select cmd, policyname from pg_policies
--    where schemaname = 'public' and tablename = '<table>' order by cmd;

with expected_policies(sch, tbl, pol) as (values
${policyRows}
),
expected_functions(fn) as (values
${fnRows}
)
select 'MISSING POLICY' as what, sch || '.' || tbl as name, pol as detail
  from expected_policies e
 where not exists (
         select 1 from pg_policies p
          where p.schemaname = e.sch
            and p.tablename  = e.tbl
            and p.policyname = e.pol)

union all

select 'MISSING FUNCTION', fn, ''
  from expected_functions f
 where not exists (
         select 1
           from pg_proc pr
           join pg_namespace n on n.oid = pr.pronamespace
          where n.nspname = 'public'
            and pr.proname = f.fn)

 order by 1, 2;
`;

const flag = process.argv.indexOf('-o');
if (flag !== -1 && process.argv[flag + 1]) {
  writeFileSync(process.argv[flag + 1], out);
  console.error(`wrote ${process.argv[flag + 1]} — ${expected.length} policies, ${functions.size} functions`);
} else {
  process.stdout.write(out);
}
